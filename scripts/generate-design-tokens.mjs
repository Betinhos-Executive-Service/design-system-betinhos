import { pathToFileURL } from "node:url";
import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const DOLLAR = "$";
const VALUE = `${DOLLAR}value`;
const TYPE = `${DOLLAR}type`;
const EXTENSIONS = `${DOLLAR}extensions`;
export const MARKDOWN_TOKENS_START = "<!-- GENERATED:TOKENS_CSS:START -->";
export const MARKDOWN_TOKENS_END = "<!-- GENERATED:TOKENS_CSS:END -->";

function isToken(value) {
  return Boolean(value && typeof value === "object" && !Array.isArray(value) && VALUE in value);
}

function collectTokens(node, path = [], inheritedType = null, result = new Map()) {
  if (!node || typeof node !== "object" || Array.isArray(node)) return result;

  const currentType = node[TYPE] || inheritedType;
  for (const [key, value] of Object.entries(node)) {
    if (key.startsWith(DOLLAR)) continue;
    const tokenPath = [...path, key];
    if (isToken(value)) {
      result.set(tokenPath.join("."), {
        path: tokenPath.join("."),
        type: value[TYPE] || currentType,
        value: value[VALUE],
      });
      continue;
    }
    collectTokens(value, tokenPath, value?.[TYPE] || currentType, result);
  }
  return result;
}

function compactPath(path) {
  const parts = path.split(".");
  if (parts[0] === "color" && ["primitive", "semantic"].includes(parts[1])) parts.splice(1, 1);
  if (parts[0] === "component") parts.shift();
  if (parts[0] === "motion" && parts[1] === "duration") parts.shift();
  if (parts[0] === "motion" && parts[1] === "easing") parts.splice(0, 2, "ease");
  if (parts[0] === "layout" && parts[1] === "breakpoint") parts.shift();
  if (parts[0] === "size" && parts[1]?.startsWith("font-")) {
    parts.splice(0, 2, "font", `size-${parts[1].slice(5)}`);
  }
  return parts.join("-");
}

function cssVariable(path, prefix = "bt") {
  return `--${prefix}-${compactPath(path)}`;
}

function referencePath(value) {
  if (typeof value !== "string" || !value.startsWith("{") || !value.endsWith("}")) return null;
  return value.slice(1, -1);
}

function dimension(value) {
  return `${value.value}${value.unit}`;
}

function fontFamily(value) {
  return value
    .map((family) => (/^(serif|sans-serif|monospace|system-ui)$/i.test(family) ? family : `"${family}"`))
    .join(", ");
}

function color(value) {
  const alpha = value.alpha ?? 1;
  if (alpha === 1 && value.hex) return value.hex.toLowerCase();
  const [red, green, blue] = value.components.map((component) => Math.round(component * 255));
  return `rgba(${red}, ${green}, ${blue}, ${alpha})`;
}

function shadowLayer(value) {
  return `${dimension(value.offsetX)} ${dimension(value.offsetY)} ${dimension(value.blur)} ${dimension(value.spread)} ${color(value.color)}`;
}

function primitiveCss(value, type, prefix) {
  const reference = referencePath(value);
  if (reference) return `var(${cssVariable(reference, prefix)})`;

  switch (type) {
    case "color": return color(value);
    case "dimension":
    case "duration": return dimension(value);
    case "fontFamily": return fontFamily(value);
    case "fontWeight":
    case "number":
    case "boolean": return String(value);
    case "string": return value;
    case "cubicBezier": return `cubic-bezier(${value.join(", ")})`;
    case "shadow": return (Array.isArray(value) ? value : [value]).map(shadowLayer).join(", ");
    default: throw new Error(`Tipo DTCG sem saída CSS: ${type}`);
  }
}

function typographyProperties(token, prefix) {
  const properties = [];
  for (const [property, value] of Object.entries(token.value)) {
    const suffix = property.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`);
    const reference = referencePath(value);
    let cssValue;
    if (reference) {
      cssValue = `var(${cssVariable(reference, prefix)})`;
    } else if (property === "fontFamily") {
      cssValue = fontFamily(value);
    } else if (["fontSize", "letterSpacing"].includes(property)) {
      cssValue = dimension(value);
    } else {
      cssValue = String(value);
    }
    properties.push(`  ${cssVariable(`${token.path}.${suffix}`, prefix)}: ${cssValue};`);
  }
  return properties;
}

export function generateCss(document) {
  const metadata = document[EXTENSIONS]?.["com.betinhos.design-system"] || {};
  const prefix = metadata.cssPrefix || "bt";
  const tokens = collectTokens(document);
  const lines = [
    `/* Betinhos Design System ${metadata.version || "unversioned"}.`,
    " * GENERATED from design-tokens.json. Do not edit this file manually.",
    " */",
    ":root {",
  ];

  let lastGroup = null;
  for (const token of tokens.values()) {
    const group = token.path.split(".")[0];
    if (group !== lastGroup) {
      if (lastGroup !== null) lines.push("");
      lines.push(`  /* ${group} */`);
      lastGroup = group;
    }
    if (!token.type) throw new Error(`Token sem tipo: ${token.path}`);
    if (token.type === "typography") {
      lines.push(...typographyProperties(token, prefix));
    } else {
      lines.push(`  ${cssVariable(token.path, prefix)}: ${primitiveCss(token.value, token.type, prefix)};`);
    }
  }

  const compatibility = metadata.compatibilityAliases || {};
  if (Object.keys(compatibility).length) {
    lines.push("", "  /* Compatibility aliases */");
    for (const [alias, target] of Object.entries(compatibility)) {
      lines.push(`  --${prefix}-${alias}: var(${cssVariable(target, prefix)});`);
    }
  }

  const legacy = metadata.legacyAliases || {};
  if (Object.keys(legacy).length) {
    lines.push("", "  /* Source-app legacy aliases */");
    for (const [alias, target] of Object.entries(legacy)) {
      lines.push(`  --${alias}: var(${cssVariable(target, prefix)});`);
    }
  }

  lines.push("}", "", "@media (prefers-reduced-motion: reduce) {", "  *, *::before, *::after {", "    scroll-behavior: auto !important;", "    animation-duration: .01ms !important;", "    animation-iteration-count: 1 !important;", "    transition-duration: .01ms !important;", "  }", "}", "");
  return lines.join("\n");
}

export async function loadTokenDocument(path = resolve("design-tokens.json")) {
  return JSON.parse(await readFile(path, "utf8"));
}

export function synchronizeMarkdownSnapshot(markdown, css) {
  const start = markdown.indexOf(MARKDOWN_TOKENS_START);
  const end = markdown.indexOf(MARKDOWN_TOKENS_END);
  if (start < 0 || end < 0 || end <= start) {
    throw new Error("Marcadores do snapshot de tokens ausentes ou inválidos em DESIGN_SYSTEM.md.");
  }
  const before = markdown.slice(0, start + MARKDOWN_TOKENS_START.length);
  const after = markdown.slice(end);
  return `${before}\n\`\`\`css\n${css.trimEnd()}\n\`\`\`\n${after}`;
}

async function main() {
  const document = await loadTokenDocument();
  const css = generateCss(document);
  const markdownPath = resolve("DESIGN_SYSTEM.md");
  const markdown = await readFile(markdownPath, "utf8");
  // O pacote @betinhos/tokens leva cópias exatas do CSS e do JSON (os apps instalam por versão).
  const json = await readFile(resolve("design-tokens.json"), "utf8");
  await Promise.all([
    writeFile(resolve("design-tokens.css"), css, "utf8"),
    writeFile(resolve("packages/tokens/design-tokens.css"), css, "utf8"),
    writeFile(resolve("packages/tokens/design-tokens.json"), json, "utf8"),
    writeFile(markdownPath, synchronizeMarkdownSnapshot(markdown, css), "utf8"),
  ]);
  console.log("CSS e snapshot Markdown gerados a partir de design-tokens.json.");
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  main().catch((error) => {
    console.error(error.message);
    process.exitCode = 1;
  });
}
